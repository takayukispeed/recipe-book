#!/usr/bin/env python3
"""Regenerate INDEX.md from the front matter of recipes/ and meals/.

Usage: python3 scripts/build_index.py
"""
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def front_matter(path):
    """Parse the simple `key: value` front matter between --- lines."""
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        return {}
    meta = {}
    for line in lines[1:]:
        if line.strip() == "---":
            break
        key, _, value = line.partition(":")
        value = value.strip()
        if value.startswith("[") and value.endswith("]"):
            value = [v.strip() for v in value[1:-1].split(",") if v.strip()]
        meta[key.strip()] = value
    return meta


def entries(folder):
    for path in sorted((ROOT / folder).glob("*.md")):
        meta = front_matter(path)
        meta.setdefault("title", path.stem)
        meta["link"] = f"{folder}/{path.name}"
        yield meta


def main():
    recipes = list(entries("recipes"))
    meals = list(entries("meals"))

    out = ["# Index", "", "_Generated by `scripts/build_index.py`. Do not edit by hand._", ""]

    out += ["## Recipes", "", "| Recipe | Type | Serves | Tags |", "|---|---|---|---|"]
    for r in sorted(recipes, key=lambda r: r["title"].lower()):
        kind = "full method" if r.get("type") == "full" else "ingredients only"
        tags = ", ".join(r.get("tags") or [])
        out.append(f"| [{r['title']}]({r['link']}) | {kind} | {r.get('serves', '')} | {tags} |")

    by_tag = defaultdict(list)
    for r in recipes:
        for tag in r.get("tags") or ["untagged"]:
            by_tag[tag].append(r)
    out += ["", "## By tag", ""]
    for tag in sorted(by_tag):
        links = ", ".join(f"[{r['title']}]({r['link']})" for r in by_tag[tag])
        out.append(f"- **{tag}**: {links}")

    out += ["", "## Meals", ""]
    out += [f"- [{m['title']}]({m['link']})" for m in meals] or ["_None yet._"]

    (ROOT / "INDEX.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"INDEX.md: {len(recipes)} recipes, {len(meals)} meals")


if __name__ == "__main__":
    main()
